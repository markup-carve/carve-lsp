#!/usr/bin/env node
// Writes src/carve-grammar.ts from the carve-grammars TextMate grammar at one commit.
//
//   node tools/sync-grammar.mjs <40-hex carve-grammars commit>
//
// The grammar is vendored rather than installed: a git dependency cannot be
// published (tools/no-git-dependencies.mjs), and the commit is the pin.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const rev = process.argv[2]
if (!/^[0-9a-f]{40}$/.test(rev ?? '')) {
  console.error('usage: node tools/sync-grammar.mjs <40-hex carve-grammars commit>')
  process.exit(2)
}
const url = `https://raw.githubusercontent.com/markup-carve/carve-grammars/${rev}/textmate/carve.tmLanguage.json`
const response = await fetch(url)
if (!response.ok) throw new Error(`${url}: ${response.status}`)
const grammar = await response.json()
if (grammar.scopeName !== 'source.carve') throw new Error(`${url}: scopeName is ${grammar.scopeName}`)
const target = fileURLToPath(new URL('../src/carve-grammar.ts', import.meta.url))
writeFileSync(target, `// Generated by tools/sync-grammar.mjs; do not edit.
// The carve-grammars TextMate grammar (textmate/carve.tmLanguage.json) at CARVE_GRAMMARS_REV.
export const CARVE_GRAMMARS_REV = '${rev}'

export const carveGrammarSource: string = ${JSON.stringify(JSON.stringify(grammar))}
`, 'utf8')
console.log(`wrote ${target} from carve-grammars ${rev}`)
